import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { createPgliteEngine } from "@/lib/engine/pglite-engine";
import { SUPABASE_SETUP_SQL } from "@/lib/engine/supabase-setup-sql";
import { findTable, introspect, type Catalog } from "@/lib/runner/introspect";
import { setupDatabase } from "@/lib/runner/setup";
import type { SqlEngine } from "@/lib/runner/types";

const SCHEMA = `
create role app_owner nologin;
create role app_member nologin;
create role app_admin nologin bypassrls;
grant app_owner to app_member;

create table public.docs (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null,
  tenant_id int not null,
  title varchar(80),
  doubled int generated always as (tenant_id * 2) stored,
  tripled int generated always as (tenant_id * 3) virtual,
  seq int generated by default as identity
);
alter table public.docs enable row level security;
alter table public.docs force row level security;
create policy "docs read" on public.docs for select to authenticated, anon
  using (auth.uid() = user_id);
create policy docs_write on public.docs for update to authenticated
  using (auth.uid() = user_id) with check (true);
create policy docs_tenant on public.docs as restrictive for all
  using (tenant_id = ((auth.jwt() -> 'app_metadata') ->> 'tenant_id')::int);

-- Composite key, declared in an order that differs from the column order.
create table public.memberships (
  user_id uuid not null,
  team_id int not null,
  role text not null default 'member',
  primary key (team_id, user_id)
);

-- Quoted, mixed-case identifiers and an owner that is an application role.
create table public."Audit Log" ("Entry ID" bigint primary key, "Line" text);
alter table public."Audit Log" owner to app_owner;
grant insert on public."Audit Log" to public;
revoke all on public.memberships from anon;

-- No primary key at all.
create table public.events (at timestamptz, payload jsonb);

create view public.docs_open as select id, title from public.docs;
create view public.docs_safe with (security_invoker = true) as
  select d.id, m.role from public.docs d join public.memberships m on m.user_id = d.user_id;
create materialized view public.docs_count as select count(*) as n from public.docs;

create function public.is_member(team int) returns boolean
  language sql stable security definer set search_path = public, pg_temp
  as $$ select exists (select 1 from public.memberships where team_id = team) $$;
create function public.is_member(team int, who uuid) returns boolean
  language sql stable security definer
  as $$ select exists (select 1 from public.memberships where team_id = team and user_id = who) $$;
create function public.plain() returns int language sql as 'select 1';

create schema private;
create table private.secrets (id int primary key);
`;

describe("introspect against a real PGlite (supabase mode, legacy grants)", () => {
  let engine: SqlEngine;
  let catalog: Catalog;

  beforeAll(async () => {
    engine = await createPgliteEngine();
    await setupDatabase(
      engine,
      { mode: "supabase", schemaSql: SCHEMA, seedSql: "" },
      SUPABASE_SETUP_SQL,
    );
    catalog = await introspect(engine, ["public", "nope", "public"]);
  }, 60_000);

  afterAll(async () => {
    await engine.close();
  });

  it("lists only tables of the exposed schemas, in byte order, and reports missing schemas", () => {
    expect(catalog.exposedSchemas).toEqual(["public", "nope"]);
    expect(catalog.missingSchemas).toEqual(["nope"]);
    // "C" collation: upper case sorts before lower case, whatever the database locale.
    expect(catalog.tables.map((table) => `${table.schema}.${table.name}`)).toEqual([
      "public.Audit Log",
      "public.docs",
      "public.events",
      "public.memberships",
    ]);
    expect(findTable(catalog, "private", "secrets")).toBeUndefined();
    expect(findTable(catalog, "public", "audit log")).toBeUndefined();
  });

  it("reports owner, RLS flags and FORCE per table", () => {
    expect(findTable(catalog, "public", "docs")).toMatchObject({
      owner: "postgres",
      rlsEnabled: true,
      rlsForced: true,
      partitioned: false,
    });
    expect(findTable(catalog, "public", "Audit Log")).toMatchObject({
      owner: "app_owner",
      rlsEnabled: false,
      rlsForced: false,
    });
  });

  it("describes columns: type, not null, default, generated (stored and virtual) and identity", () => {
    expect(findTable(catalog, "public", "docs")?.columns).toEqual([
      {
        name: "id",
        position: 1,
        type: "uuid",
        notNull: true,
        default: "gen_random_uuid()",
        generated: null,
        generationExpression: null,
        identity: null,
      },
      {
        name: "user_id",
        position: 2,
        type: "uuid",
        notNull: true,
        default: null,
        generated: null,
        generationExpression: null,
        identity: null,
      },
      {
        name: "tenant_id",
        position: 3,
        type: "integer",
        notNull: true,
        default: null,
        generated: null,
        generationExpression: null,
        identity: null,
      },
      {
        name: "title",
        position: 4,
        type: "character varying(80)",
        notNull: false,
        default: null,
        generated: null,
        generationExpression: null,
        identity: null,
      },
      {
        name: "doubled",
        position: 5,
        type: "integer",
        notNull: false,
        default: null,
        generated: "stored",
        generationExpression: "(tenant_id * 2)",
        identity: null,
      },
      {
        name: "tripled",
        position: 6,
        type: "integer",
        notNull: false,
        default: null,
        generated: "virtual",
        generationExpression: "(tenant_id * 3)",
        identity: null,
      },
      {
        name: "seq",
        position: 7,
        type: "integer",
        notNull: true,
        default: null,
        generated: null,
        generationExpression: null,
        identity: "by default",
      },
    ]);
  });

  it("returns primary key columns in KEY order, quoted names verbatim, and none for a keyless table", () => {
    expect(findTable(catalog, "public", "memberships")?.primaryKey).toEqual(["team_id", "user_id"]);
    expect(findTable(catalog, "public", "Audit Log")?.primaryKey).toEqual(["Entry ID"]);
    expect(findTable(catalog, "public", "docs")?.primaryKey).toEqual(["id"]);
    expect(findTable(catalog, "public", "events")?.primaryKey).toEqual([]);
  });

  it("reads policies: command, permissive or restrictive, roles, USING and WITH CHECK", () => {
    expect(catalog.policies).toEqual([
      {
        schema: "public",
        table: "docs",
        name: "docs read",
        command: "select",
        permissive: true,
        roles: ["anon", "authenticated"],
        using: "(auth.uid() = user_id)",
        withCheck: null,
      },
      {
        schema: "public",
        table: "docs",
        name: "docs_tenant",
        command: "all",
        permissive: false,
        roles: ["PUBLIC"],
        using:
          "(tenant_id = (((auth.jwt() -> 'app_metadata'::text) ->> 'tenant_id'::text))::integer)",
        withCheck: null,
      },
      {
        schema: "public",
        table: "docs",
        name: "docs_write",
        command: "update",
        permissive: true,
        roles: ["authenticated"],
        using: "(auth.uid() = user_id)",
        withCheck: "true",
      },
    ]);
  });

  it("lists table privileges per role, PUBLIC and the implicit owner privileges included", () => {
    const of = (table: string, grantee: string) =>
      catalog.tablePrivileges
        .filter((entry) => entry.table === table && entry.grantee === grantee)
        .map((entry) => entry.privilege);

    // RLS006: a write command granted to PUBLIC.
    expect(of("Audit Log", "PUBLIC")).toEqual(["INSERT"]);
    // Legacy default grants reach a table created afterwards ...
    expect(of("docs", "anon")).toEqual(
      expect.arrayContaining(["DELETE", "INSERT", "SELECT", "UPDATE"]),
    );
    // ... and the user's REVOKE after them survives.
    expect(of("memberships", "anon")).toEqual([]);
    expect(of("memberships", "authenticated")).toContain("SELECT");
    // The owner's privileges come from acldefault() when relacl is NULL, and are sorted.
    const owner = of("Audit Log", "app_owner");
    expect(owner).toContain("SELECT");
    expect(owner).toEqual([...owner].sort());
  });

  it("lists the privileges of views and materialized views too (RLS008 needs them)", () => {
    const granteesOf = (relation: string) =>
      new Set(
        catalog.tablePrivileges
          .filter((entry) => entry.table === relation && entry.privilege === "SELECT")
          .map((entry) => entry.grantee),
      );

    // Measured on PostgreSQL 18.3: the legacy default grants (ALTER DEFAULT PRIVILEGES ON TABLES)
    // reach views and materialized views like tables; the owner's rights are implicit.
    for (const relation of ["docs_open", "docs_safe", "docs_count"]) {
      expect([...granteesOf(relation)].sort(), relation).toEqual([
        "anon",
        "authenticated",
        "postgres",
        "service_role",
      ]);
    }
  });

  it("reports role attributes and memberships for every non-system role", () => {
    const byName = new Map(catalog.roles.map((role) => [role.name, role]));
    expect([...byName.keys()]).toEqual([
      "anon",
      "app_admin",
      "app_member",
      "app_owner",
      "authenticated",
      "postgres",
      "service_role",
    ]);
    expect(byName.get("postgres")).toMatchObject({ superuser: true, bypassRls: true });
    expect(byName.get("service_role")).toMatchObject({ superuser: false, bypassRls: true });
    expect(byName.get("app_admin")).toMatchObject({ bypassRls: true });
    expect(byName.get("anon")).toMatchObject({
      superuser: false,
      bypassRls: false,
      inherit: false,
      canLogin: false,
      memberOf: [],
    });
    // Ownership is reachable through membership: the guard needs this edge.
    expect(byName.get("app_member")).toMatchObject({ inherit: true, memberOf: ["app_owner"] });
  });

  it("reads views: definition, security_invoker and the relations they depend on", () => {
    expect(catalog.views.map((view) => view.name)).toEqual([
      "docs_count",
      "docs_open",
      "docs_safe",
    ]);
    const [count, open, safe] = catalog.views;
    expect(open).toMatchObject({
      schema: "public",
      owner: "postgres",
      materialized: false,
      securityInvoker: false,
      references: [{ schema: "public", name: "docs", kind: "table" }],
    });
    expect(open?.definition).toContain("FROM docs");
    expect(safe).toMatchObject({
      securityInvoker: true,
      references: [
        { schema: "public", name: "docs", kind: "table" },
        { schema: "public", name: "memberships", kind: "table" },
      ],
    });
    expect(count).toMatchObject({ materialized: true, securityInvoker: false });
  });

  it("reads functions: SECURITY DEFINER, pinned search_path, owner, overloads told apart", () => {
    expect(catalog.functions).toEqual([
      {
        schema: "public",
        name: "is_member",
        identityArguments: "team integer",
        kind: "function",
        owner: "postgres",
        language: "sql",
        securityDefiner: true,
        searchPath: "public, pg_temp",
      },
      {
        schema: "public",
        name: "is_member",
        identityArguments: "team integer, who uuid",
        kind: "function",
        owner: "postgres",
        language: "sql",
        securityDefiner: true,
        searchPath: null,
      },
      {
        schema: "public",
        name: "plain",
        identityArguments: "",
        kind: "function",
        owner: "postgres",
        language: "sql",
        securityDefiner: false,
        searchPath: null,
      },
    ]);
  });

  it("is deterministic and works on a transaction handle", async () => {
    const again = await introspect(engine, ["public", "nope"]);
    expect(JSON.stringify(again)).toBe(JSON.stringify(catalog));
    const inside = await engine.transaction((tx) => introspect(tx, ["public", "nope"]));
    expect(JSON.stringify(inside)).toBe(JSON.stringify(catalog));
  });

  it("sees another schema only when asked for it", async () => {
    const both = await introspect(engine, ["private", "public"]);
    expect(both.missingSchemas).toEqual([]);
    expect(both.tables.map((table) => `${table.schema}.${table.name}`)).toEqual([
      "private.secrets",
      "public.Audit Log",
      "public.docs",
      "public.events",
      "public.memberships",
    ]);
    const none = await introspect(engine, []);
    expect(none).toMatchObject({ tables: [], policies: [], views: [], functions: [] });
  });
});
