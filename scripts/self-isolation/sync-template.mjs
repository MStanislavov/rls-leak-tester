#!/usr/bin/env node
/**
 * Keeps the fourth template in step with the migrations.
 *
 * `src/lib/scenario` is pure and cannot read files, so the template "own-scenarios-table" carries
 * the SQL of `supabase/migrations` as a string in a generated module. This script writes that
 * module; `tests/templates/own-scenarios-table.test.ts` fails when the two differ.
 *
 *   node scripts/self-isolation/sync-template.mjs           regenerate the module
 *   node scripts/self-isolation/sync-template.mjs --check   exit 1 when it is out of date
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");

export const MIGRATIONS_DIRECTORY = "supabase/migrations";
export const MODULE_PATH = "src/lib/scenario/templates/own-scenarios-migrations.ts";
export const CONSTANT_NAME = "OWN_SCENARIOS_MIGRATIONS_SQL";

/** The migration files in the order Supabase applies them: by file name. */
export function migrationFiles(root = REPO_ROOT) {
  return readdirSync(path.join(root, MIGRATIONS_DIRECTORY))
    .filter((name) => name.endsWith(".sql"))
    .sort((a, b) => (a < b ? -1 : 1));
}

/** Every migration, in order, joined by a newline. One file: exactly that file. */
export function readMigrationsSql(root = REPO_ROOT) {
  return migrationFiles(root)
    .map((name) => readFileSync(path.join(root, MIGRATIONS_DIRECTORY, name), "utf8"))
    .join("\n");
}

function escapeTemplateLiteral(text) {
  return text.replaceAll("\\", "\\\\").replaceAll("`", "\\`").replaceAll("${", "\\${");
}

/** The generated module. Its form is stable under Prettier, so a commit hook leaves it alone. */
export function renderModule(sql, files = migrationFiles()) {
  return `/**
 * GENERATED by scripts/self-isolation/sync-template.mjs. Do not edit: change the migration and
 * run the script. Source: ${files.map((name) => `${MIGRATIONS_DIRECTORY}/${name}`).join(", ")}.
 *
 * The SQL of the app's own \`scenarios\` table (brief 3.10), byte for byte. A test compares it with
 * the files, so the template "own-scenarios-table" always tests what is deployed.
 */
export const ${CONSTANT_NAME} = \`${escapeTemplateLiteral(sql)}\`;
`;
}

function main(argv) {
  const target = path.join(REPO_ROOT, MODULE_PATH);
  const wanted = renderModule(readMigrationsSql());
  if (argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(target, "utf8");
    } catch {
      current = "";
    }
    if (current !== wanted) {
      console.error(
        `${MODULE_PATH} is out of date. Run: node scripts/self-isolation/sync-template.mjs`,
      );
      process.exitCode = 1;
      return;
    }
    console.log(`${MODULE_PATH} matches ${MIGRATIONS_DIRECTORY}.`);
    return;
  }
  writeFileSync(target, wanted);
  console.log(`Wrote ${MODULE_PATH} from ${migrationFiles().length} migration file(s).`);
}

if (
  process.argv[1] !== undefined &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  main(process.argv.slice(2));
}
