"use client";

/**
 * "Export CI check" (brief 3.8): a toolbar button and a dialog that previews
 * `rls-isolation.test.sql` and `rls-isolation.yml` and downloads them. The files are generated
 * from the lab's last run, so the dialog only shows them while that run is a run of the current
 * scenario text; otherwise it says so and offers the run.
 */
import { Download, FileCode2, Play } from "lucide-react";
import { useMemo, useState } from "react";
import { Button } from "@/components/ui/button";
import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogHeader,
  DialogTitle,
} from "@/components/ui/dialog";
import { Tabs, TabsContent, TabsList, TabsTrigger } from "@/components/ui/tabs";
import type { CiExportFile } from "@/lib/export";
import {
  buildCiExportView,
  ciExportReadiness,
  type CiExportReadiness,
  type CiExportView,
} from "@/lib/lab/export-ci";
import type { SupabaseSetupSql } from "@/lib/runner";
import { CopyButton } from "../copy-button";
import { loadLabPorts } from "../lab-engine";
import type { LabSlotProps } from "../lab-extensions";
import { downloadFile } from "./download-file";

const WAITING: Record<Exclude<CiExportReadiness, "ready" | "stale">, string> = {
  running: "Running the matrix. The files appear here when the run is done.",
  "no-run":
    "There is no completed run to export from. Close this dialog, fix what the lab reports, and run again.",
};

function FilePanel({ file }: { readonly file: CiExportFile }) {
  return (
    <div className="flex min-w-0 flex-col gap-1.5">
      <div className="flex flex-wrap items-center justify-between gap-2">
        <p className="min-w-0 text-xs text-muted-foreground">
          Goes to <code className="font-mono break-all text-foreground">{file.path}</code>
        </p>
        <div className="flex items-center gap-1">
          <CopyButton
            text={file.content}
            label={`Copy ${file.name}`}
            testId={`export-ci-copy-${file.name}`}
          />
          <Button
            type="button"
            variant="ghost"
            size="xs"
            aria-label={`Download ${file.name}`}
            data-testid={`export-ci-download-${file.name}`}
            onClick={() => downloadFile(file)}
          >
            <Download aria-hidden="true" />
            Download
          </Button>
        </div>
      </div>
      <pre
        tabIndex={0}
        role="group"
        aria-label={`${file.name}, read-only`}
        data-testid={`export-ci-preview-${file.name}`}
        className="h-72 overflow-auto rounded-md border bg-muted p-2 font-mono text-xs whitespace-pre"
      >
        {file.content}
      </pre>
    </div>
  );
}

function ExportFiles({ view }: { readonly view: CiExportView }) {
  const [test] = view.proof;
  return (
    <div className="flex min-w-0 flex-col gap-3" data-testid="export-ci-files">
      {view.warnings.length > 0 ? (
        <div
          role="alert"
          data-testid="export-ci-warnings"
          className="flex flex-col gap-1 rounded-md border border-destructive/50 p-2 text-sm"
        >
          <p className="font-medium">This check would not pass in CI as it is.</p>
          <ul className="list-disc pl-5">
            {view.warnings.map((warning) => (
              <li key={warning}>{warning}</li>
            ))}
          </ul>
        </div>
      ) : null}
      <Tabs defaultValue={test.name}>
        <TabsList aria-label="Exported files">
          {view.proof.map((file) => (
            <TabsTrigger
              key={file.name}
              value={file.name}
              data-testid={`export-ci-tab-${file.name}`}
            >
              {file.name}
            </TabsTrigger>
          ))}
        </TabsList>
        {view.proof.map((file) => (
          <TabsContent key={file.name} value={file.name}>
            <FilePanel file={file} />
          </TabsContent>
        ))}
      </Tabs>

      <div className="flex flex-col gap-1.5 text-sm" data-testid="export-ci-note">
        <p>
          Put the workflow at <code className="font-mono">{view.workflowPath}</code> and the SQL
          files in <code className="font-mono">{view.sqlDirectory}/</code> at the root of your
          repository. The verdict in CI comes from the same probes as the matrix here: the test file
          is generated by the probe builders the runner uses, so the two cannot drift.
        </p>
        <p data-testid="export-ci-outcome" data-failing-cells={view.failingCells}>
          {view.outcome}
        </p>
      </div>

      <div className="flex flex-col gap-1.5 rounded-md border p-2 text-sm">
        <p>
          The workflow loads {view.companions.length === 1 ? "this file" : "these files"} before the
          test. They are your scenario as it is; point the workflow at your own migrations and seed
          instead when you have them.
        </p>
        <ul className="flex flex-wrap gap-1.5">
          {view.companions.map((file) => (
            <li key={file.name}>
              <Button
                type="button"
                variant="outline"
                size="xs"
                data-testid={`export-ci-download-${file.name}`}
                onClick={() => downloadFile(file)}
              >
                <Download aria-hidden="true" />
                <span className="font-mono">{file.name}</span>
              </Button>
            </li>
          ))}
        </ul>
      </div>

      <div className="flex flex-wrap items-center justify-end gap-2">
        {/* A row of its own: beside the two buttons it made the second one wrap alone. */}
        <p className="basis-full text-xs text-muted-foreground sm:text-right">
          Each file is a download of its own; the browser may ask once whether to allow several.
        </p>
        <Button
          type="button"
          variant="outline"
          data-testid="export-ci-download-all"
          onClick={() => [...view.companions, ...view.proof].forEach(downloadFile)}
        >
          <Download aria-hidden="true" />
          Download all {view.companions.length + view.proof.length} files
        </Button>
        <Button
          type="button"
          data-testid="export-ci-download-both"
          onClick={() => view.proof.forEach(downloadFile)}
        >
          <Download aria-hidden="true" />
          Download both files
        </Button>
      </div>
    </div>
  );
}

export function ExportCiCheck({
  busy,
  getScenario,
  matrixRun,
  resultIsStale,
  startRun,
  validation,
}: LabSlotProps) {
  const [open, setOpen] = useState(false);
  const [supabase, setSupabase] = useState<SupabaseSetupSql | null>(null);
  const [loadFailed, setLoadFailed] = useState(false);

  const scenario = validation.scenario;
  const readiness = ciExportReadiness({ busy, matrixRun, resultIsStale, scenario });

  const exported = useMemo(
    () =>
      open && readiness === "ready" && scenario !== null && matrixRun !== null && supabase !== null
        ? buildCiExportView({ scenario, run: matrixRun, supabase })
        : null,
    [open, readiness, scenario, matrixRun, supabase],
  );

  const show = (): void => {
    // Flushes the editors: text still in their debounce makes the result stale before we look.
    getScenario();
    setOpen(true);
    setLoadFailed(false);
    // The Supabase setup SQL lives with the engine; a completed run has loaded it already.
    loadLabPorts().then(
      (ports) => setSupabase(ports.supabase),
      () => setLoadFailed(true),
    );
  };

  return (
    <>
      <Button
        type="button"
        variant="outline"
        size="sm"
        disabled={matrixRun === null || busy}
        title={
          matrixRun === null ? "Run the matrix first: the export comes from a run." : undefined
        }
        data-testid="export-ci-button"
        data-readiness={readiness}
        onClick={show}
      >
        <FileCode2 aria-hidden="true" />
        Export CI check
      </Button>
      <Dialog open={open} onOpenChange={setOpen}>
        <DialogContent
          data-testid="export-ci-dialog"
          data-readiness={readiness}
          className="max-h-[calc(100dvh-2rem)] overflow-y-auto sm:max-w-3xl"
        >
          <DialogHeader>
            <DialogTitle>Export CI check</DialogTitle>
            <DialogDescription>
              Two files that keep this verdict true in your repository: the isolation proof as plain
              SQL, and a GitHub Actions workflow that runs it against a real Postgres.
            </DialogDescription>
          </DialogHeader>

          {readiness === "stale" ? (
            <div className="flex flex-col items-start gap-2" data-testid="export-ci-stale">
              <p role="status">
                The scenario changed since the last run. The export is generated from a run, so it
                would describe the old text. Run the matrix again to export the current scenario.
              </p>
              <Button type="button" data-testid="export-ci-rerun" onClick={startRun}>
                <Play aria-hidden="true" />
                Run again
              </Button>
            </div>
          ) : null}

          {readiness === "running" || readiness === "no-run" ? (
            <p role="status" data-testid="export-ci-waiting">
              {WAITING[readiness]}
            </p>
          ) : null}

          {readiness === "ready" && loadFailed ? (
            <p role="alert" data-testid="export-ci-error">
              The export could not be loaded. Check the connection and open this dialog again.
            </p>
          ) : null}

          {exported !== null && !exported.ok ? (
            <p role="alert" data-testid="export-ci-error">
              {exported.message}
            </p>
          ) : null}

          {exported !== null && exported.ok ? <ExportFiles view={exported.view} /> : null}
        </DialogContent>
      </Dialog>
    </>
  );
}
